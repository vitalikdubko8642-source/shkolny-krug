// «ИИ-помощник модерации» — в прототипе это простой алгоритм, который работает прямо в телефоне.
// В настоящей версии здесь был бы запрос к нейросети. Принцип тот же:
// ИИ только ПОДСКАЗЫВАЕТ, решение принимает человек.
//
// Что умеет:
// 1) findSimilar — ищет похожую группу/идею, чтобы не плодить одинаковые («миллиард групп»).
// 2) checkNew    — проверяет новую группу или идею: не пустая ли, нет ли телефона/адреса.

// Убираем окончания, чтобы «футбол», «футбола», «футболу» считались одним словом
const STOP = new Set(['и', 'в', 'во', 'на', 'с', 'со', 'по', 'для', 'за', 'у', 'о', 'об', 'от', 'до', 'из', 'к', 'не', 'а', 'но', 'что', 'это', 'как', 'наш', 'наша', 'наше', 'все', 'всех', 'школа', 'школы', 'школе', 'группа', 'чат'])
const stem = (w) => w.replace(/(ами|ями|ого|его|ому|ему|ыми|ими|ах|ях|ов|ев|ей|ой|ий|ый|ая|яя|ое|ее|ую|юю|ом|ем|ам|ям|ы|и|а|я|о|е|у|ю|ь)$/u, '')

export function words(text) {
  return new Set(
    text.toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я0-9]+/u)
      .filter((w) => w.length > 2 && !STOP.has(w))
      .map((w) => (w.length > 4 ? stem(w) : w)),
  )
}

// Насколько два текста похожи: доля общих слов (0…1)
export function similarity(a, b) {
  const A = words(a), B = words(b)
  if (!A.size || !B.size) return 0
  // Слова считаем одинаковыми, если совпадают целиком или первыми 5 буквами («музыка» ≈ «музыкальная»)
  const same = (x, y) => x === y || (x.length >= 5 && y.length >= 5 && x.slice(0, 5) === y.slice(0, 5))
  let common = 0
  for (const w of A) if ([...B].some((v) => same(w, v))) common++
  return common / Math.min(A.size, B.size)
}

// items — список { id, title, text }. Сравниваем и весь текст, и отдельно названия
// (короткие названия «Футбол после уроков» и «Футбол во дворе» — уже повод задуматься).
// Возвращает самый похожий, если он достаточно похож.
export function findSimilar(title, text, items, threshold = 0.5) {
  let best = null
  for (const it of items) {
    const s = Math.max(similarity(text, it.text), similarity(title, it.title || ''))
    if (s >= threshold && (!best || s > best.score)) best = { ...it, score: s }
  }
  return best
}

// Проверка новой группы/идеи. Возвращает список замечаний (пустой — всё хорошо).
export function checkNew(title, desc = '') {
  const notes = []
  const all = `${title} ${desc}`
  if (title.trim().length < 4) notes.push('Название слишком короткое — по нему никто не поймёт, о чём это.')
  if (/(\+7|8)[\s-]?\(?\d{3}\)?[\s-]?\d{3}[\s-]?\d{2}[\s-]?\d{2}/.test(all)) notes.push('Похоже, тут номер телефона. Личные данные лучше не публиковать.')
  if (/(ул\.|улица|дом\s*\d|кв\.|квартира)/i.test(all)) notes.push('Похоже, тут адрес. Не пиши, где кто живёт.')
  return notes
}
