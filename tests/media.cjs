const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')

;(async () => {
  const fixture = path.join(os.tmpdir(), 'school-circle-test-camera.y4m')
  const frames = [Buffer.from('YUV4MPEG2 W320 H240 F15:1 Ip A1:1 C420jpeg\n')]
  for (let i = 0; i < 90; i++) frames.push(Buffer.from('FRAME\n'), Buffer.alloc(320 * 240, 50 + i), Buffer.alloc(320 * 240 / 2, 128))
  fs.writeFileSync(fixture, Buffer.concat(frames))
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', `--use-file-for-fake-video-capture=${fixture}`] })
  const context = await browser.newContext({ viewport: { width: 320, height: 812 }, permissions: ['camera', 'microphone'] })
  const page = await context.newPage()
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5190/')
    await page.evaluate(() => localStorage.clear()); await page.reload()
    await page.getByRole('button', { name: 'Начать', exact: true }).click()
    await page.locator('.check input').check(); await page.getByRole('button', { name: 'Дальше', exact: true }).click()
    await page.getByRole('button', { name: /Заполнить пустые поля/ }).click()
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    await page.getByRole('button', { name: 'Пропустить' }).click()
    await page.locator('.tabbar button', { hasText: 'Чаты' }).click()
    await page.locator('.chat-row').filter({ hasText: 'Гитара и музыка' }).first().click()
    await page.locator('.composer textarea').fill('Привет')
    await page.getByRole('button', { name: 'Эмодзи', exact: true }).click()
    await page.getByRole('button', { name: 'Добавить 😀' }).click()
    assert.equal(await page.locator('.composer textarea').inputValue(), 'Привет😀')
    await page.getByRole('button', { name: 'Отправить', exact: true }).click()
    await page.getByText('Привет😀', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Закрыть эмодзи' }).click()
    for (const kind of ['audio', 'video']) {
      await page.getByRole('button', { name: 'Записать голосовое или видеокружок' }).click()
      if (kind === 'video') await page.getByRole('button', { name: 'Кружок', exact: true }).click()
      await page.getByRole('button', { name: 'Начать запись' }).click()
      await page.getByText(/Запись 0:/).waitFor()
      if (kind === 'video') await page.locator('video[aria-label="Предпросмотр камеры"]').waitFor()
      await page.waitForTimeout(kind === 'video' ? 4000 : 1200)
      await page.getByRole('button', { name: 'Закончить' }).click()
      const preview = page.locator(`.record-preview ${kind === 'video' ? 'video' : 'audio'}`)
      await preview.waitFor()
      assert.equal(await preview.evaluate(el => el.readyState > 0 || !!el.src), true)
      await page.locator('.record-actions').getByRole('button', { name: 'Отправить' }).click()
      const player = page.locator(`.media-message.${kind} ${kind}`)
      await player.waitFor()
      console.log(kind, await player.evaluate(async el => { const r = await fetch(el.src); const b = await r.blob(); return { type: b.type, size: b.size, canPlay: el.canPlayType(b.type) } }))
      await player.evaluate(el => el.play())
      assert.equal(await player.evaluate(el => el.paused), false)
      await player.evaluate(el => el.pause())
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.reload()
    await page.locator('.media-message.audio audio').waitFor()
    await page.locator('.media-message.video video').waitFor()
    await page.getByRole('button', { name: 'Действия с записью' }).last().click()
    await page.getByRole('button', { name: 'Удалить', exact: true }).click()
    await page.locator('.sheet').getByRole('button', { name: 'Удалить', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('.media-message.video'))
    assert.equal(await page.locator('.media-message.video').count(), 0)
    await page.reload()
    assert.equal(await page.locator('.media-message.video').count(), 0)
    await page.evaluate(() => { navigator.mediaDevices.getUserMedia = async () => { throw new DOMException('Permission denied', 'NotAllowedError') } })
    await page.getByRole('button', { name: 'Записать голосовое или видеокружок' }).click()
    await page.getByRole('button', { name: 'Начать запись' }).click()
    await page.getByRole('alert').getByText(/Нет доступа/).waitFor()
    await page.getByRole('button', { name: 'Закрыть запись' }).click()
    assert.deepEqual(errors, [])
    console.log('Emoji insertion, fake-device audio/video recording, preview, playback, persistence and deletion passed at 320px.')
  } finally { await browser.close(); fs.unlinkSync(fixture) }
})().catch(e => { console.error(e); process.exitCode = 1 })
