const { chromium } = require('playwright-core')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const [code] = JSON.parse(fs.readFileSync(process.env.JURY_CODES_FILE, 'utf8'))
const url = process.env.JURY_TEST_URL || 'http://127.0.0.1:5193/'
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--disable-gpu'] })
  try {
    const context = await browser.newContext({ viewport: { width: 375, height: 812 } })
    const page = await context.newPage()
    await page.goto(url)
    await page.getByRole('button', { name: 'Начать', exact: true }).click()
    await page.getByRole('checkbox').check()
    await page.getByRole('button', { name: 'Дальше' }).click()
    await page.getByRole('button', { name: /Заполнить пустые поля/ }).click()
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    await page.getByRole('button', { name: 'Пропустить' }).click()
    await page.locator('.tabbar button', { hasText: 'Профиль' }).click()
    await page.getByRole('button', { name: /Войти как жюри/ }).click()
    await page.getByLabel('Код жюри').fill(code)
    await page.getByRole('button', { name: 'Продолжить' }).click()
    await page.getByRole('button', { name: 'Перейти в приложение' }).click()
    await page.getByRole('button', { name: /9В — наш класс/ }).click()
    await page.getByRole('heading', { name: '9В — наш класс' }).waitFor()
    await page.getByRole('button', { name: 'Назад' }).click()
    await page.locator('.tabbar button', { hasText: 'Профиль' }).click()
    await page.getByRole('button', { name: /Вернуться к профилю ученика/ }).click()
    await page.getByText('new_hero', { exact: true }).first().waitFor()
    await page.reload()
    await page.getByText('new_hero', { exact: true }).first().waitFor()
    await page.getByRole('button', { name: /Войти как жюри/ }).click()
    await page.getByRole('button', { name: /Вернуться к профилю ученика/ }).waitFor()
    const other = await browser.newContext()
    const otherPage = await other.newPage()
    await otherPage.goto(url)
    await otherPage.getByRole('button', { name: 'Начать', exact: true }).waitFor()
    assert.equal(await otherPage.evaluate(() => localStorage.getItem('shkolny-krug-v3') !== null && JSON.parse(localStorage.getItem('shkolny-krug-v3')).user !== null), false)
    console.log('Profile switch: student preserved, jury session restored, independent browser has no student profile.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
