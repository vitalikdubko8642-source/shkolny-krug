const { chromium } = require('playwright-core')
const assert = require('node:assert/strict')
;(async () => {
  const b = await chromium.launch({ channel: 'msedge', headless: true, args: ['--disable-gpu'] })
  try {
    const p = await b.newPage({ viewport: { width: 375, height: 812 } })
    const errors = []; p.on('pageerror', e => errors.push(e.message))
    await p.goto(process.env.TEST_URL || 'http://127.0.0.1:5193/')
    await p.getByRole('button', { name: 'Начать', exact: true }).click()
    await p.getByRole('checkbox').check(); await p.getByRole('button', { name: 'Дальше' }).click()
    await p.getByRole('button', { name: /Заполнить пустые поля/ }).click(); await p.getByRole('button', { name: 'Готово', exact: true }).click(); await p.getByRole('button', { name: 'Пропустить' }).click()
    await p.locator('.tabbar button', { hasText: 'Чаты' }).click()
    await p.getByRole('button', { name: /9Б — наш класс/ }).click()
    const msg = p.locator('.messages .msg').filter({ hasText: 'кто сделал алгебру' }).first()
    await msg.click(); await p.getByRole('button', { name: 'Сохранить в избранном' }).click()
    await p.getByRole('button', { name: 'Назад', exact: true }).click()
    await p.getByRole('button', { name: /Избранное/ }).click()
    await p.getByText('кто сделал алгебру? номер 214 вообще не понимаю').waitFor()
    await p.getByRole('button', { name: 'Назад', exact: true }).click()
    await p.getByRole('button', { name: /9Б — наш класс/ }).click()
    await p.getByRole('button', { name: 'О чате' }).click(); await p.getByRole('button', { name: 'Убрать в архив' }).click()
    assert.equal(await p.getByRole('button', { name: /9Б — наш класс/ }).count(), 0)
    await p.getByRole('button', { name: /Архив 1/ }).click(); await p.getByRole('button', { name: /9Б — наш класс/ }).click()
    await p.getByRole('button', { name: 'О чате' }).click(); await p.getByRole('button', { name: 'Вернуть из архива' }).click()
    await p.getByRole('button', { name: 'Все', exact: true }).click()
    await p.getByRole('button', { name: /9Б — наш класс/ }).waitFor()
    await p.reload(); await p.getByRole('button', { name: /Избранное/ }).click()
    await p.getByText('кто сделал алгебру? номер 214 вообще не понимаю').waitFor()
    assert.deepEqual(errors, [])
    console.log('Saved messages and archive persist and restore correctly.')
  } finally { await b.close() }
})().catch(e => { console.error(e); process.exit(1) })
