    const direct = await api('dm-request', { token: a.data.token, nick: 'direct_gamma' })
    assert.equal(direct.data.status, 'accepted')
    assert.equal((await api('dm-send', { token: a.data.token, id: direct.data.id, text: 'Без запроса' })).status, 200)
    assert.equal(await pa.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
