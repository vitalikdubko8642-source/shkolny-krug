const { chromium } = require('playwright-core')
const assert = require('node:assert/strict')
const url = process.env.DIRECT_TEST_URL || 'http://127.0.0.1:5194/'
const apiUrl = process.env.DIRECT_TEST_API || 'http://127.0.0.1:8794'
async function api(action, payload) {
  const r = await fetch(`${apiUrl}/${action}`, { method: 'POST', headers: { Origin: new URL(url).origin, 'Content-Type': 'application/json' }, body: JSON.stringify(payload) })
  return { status: r.status, data: await r.json() }
}
