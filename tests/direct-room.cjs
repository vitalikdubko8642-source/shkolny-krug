    await pa.getByRole('button', { name: 'Отправить личное сообщение' }).click()
    await pb.getByText('Привет, личная проверка!', { exact: true }).waitFor({ timeout: 12000 })
    await pb.getByText('Привет, личная проверка!', { exact: true }).click()
    await pb.getByRole('button', { name: 'Реакция ❤️' }).click()
    await pa.getByText('❤️ 1', { exact: true }).waitFor({ timeout: 12000 })
