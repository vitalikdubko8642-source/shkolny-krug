    assert.equal(await pb.locator('.jury-file video').evaluate(el => el.paused), false)
    if (process.env.DIRECT_SCREENSHOT_DIR) await pb.screenshot({ path: `${process.env.DIRECT_SCREENSHOT_DIR}/direct-chat.png` })
    assert.equal((await api('dm-poll', { token: c.data.token, id })).status, 404)
    await pb.getByRole('button', { name: 'Заблокировать', exact: true }).click()
    await pb.getByRole('button', { name: 'Разблокировать', exact: true }).waitFor()
    assert.equal((await api('dm-send', { token: a.data.token, id, text: 'Проверка' })).status, 403)
    await pb.getByRole('button', { name: 'Разблокировать', exact: true }).click()
    await pb.getByRole('button', { name: 'Назад', exact: true }).click()
    await pb.getByRole('button', { name: 'Настройки личных сообщений' }).click()
    await pb.getByText('Сначала спрашивать разрешение').waitFor()
    if (process.env.DIRECT_SCREENSHOT_DIR) await pb.screenshot({ path: `${process.env.DIRECT_SCREENSHOT_DIR}/direct-settings.png` })
    await pb.getByRole('button', { name: /Сначала спрашивать разрешение/ }).click()
