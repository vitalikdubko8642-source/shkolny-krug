const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 375, height: 812 } })
  page.setDefaultTimeout(5000)
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  try {
    await page.goto('http://127.0.0.1:5190/'); await page.evaluate(() => localStorage.clear()); await page.reload()
    await page.getByRole('button', { name: 'Начать', exact: true }).click()
    await page.locator('.check input').check(); await page.getByRole('button', { name: 'Дальше', exact: true }).click()
    await page.getByRole('button', { name: /Заполнить пустые поля/ }).click()
    await page.getByRole('button', { name: 'Готово', exact: true }).click(); await page.getByRole('button', { name: 'Пропустить' }).click()
    await page.evaluate(() => { const k = 'shkolny-krug-v3'; const s = JSON.parse(localStorage.getItem(k)); s.friends = ['pixel_cat']; s.tab = 'chats'; localStorage.setItem(k, JSON.stringify(s)) })
    await page.reload()
    await page.locator('.chat-row').filter({ hasText: 'Гитара и музыка' }).first().click()
    await page.locator('.msg .from').filter({ hasText: 'pixel_cat' }).first().click()
    await page.getByRole('button', { name: 'Открыть переписку' }).click()
    assert.match(await page.locator('.chat-head .t').innerText(), /pixel_cat/)
    await page.goBack()
    assert.match(await page.locator('.chat-head .t').innerText(), /Гитара и музыка/)
    await page.goBack()
    assert.ok(await page.locator('.chat-row').count())
    assert.deepEqual(errors, [])
    console.log('Navigation: group → direct chat → back to group → back to list passed.')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
