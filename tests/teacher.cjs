const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 375, height: 812 } })
  page.setDefaultTimeout(5000)
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  try {
    await page.goto('http://127.0.0.1:5190/')
    await page.evaluate(() => localStorage.clear()); await page.reload()
    await page.getByRole('button', { name: 'Начать', exact: true }).click()
    await page.locator('.check input').check(); await page.getByRole('button', { name: 'Дальше', exact: true }).click()
    await page.getByRole('button', { name: 'Я учитель' }).click()
    await page.getByRole('button', { name: /Заполнить пустые поля/ }).click()
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    assert.match(await page.locator('body').innerText(), /Неверный демонстрационный код/)
    await page.locator('.field').filter({ hasText: 'Демонстрационный код учителя' }).locator('input').fill('OKLA2026')
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Встречи', exact: true }).count(), 0)
    await page.getByRole('button', { name: /Создать мероприятие/ }).click()
    await page.locator('.sheet input[placeholder^="Название"]').fill('Проверка события')
    await page.locator('.sheet input[type=date]').fill('2020-01-01')
    await page.locator('.sheet input[placeholder^="Где"]').fill('Библиотека')
    assert.equal(await page.getByRole('button', { name: 'Опубликовать' }).isDisabled(), true)
    await page.locator('.sheet input[type=date]').fill('2099-01-01')
    await page.getByRole('button', { name: 'Опубликовать' }).click()
    await page.getByRole('button', { name: /Проверка события/ }).click()
    await page.getByRole('button', { name: 'Изменить', exact: true }).click()
    await page.locator('.sheet input[placeholder^="Название"]').fill('Событие изменено')
    await page.getByRole('button', { name: 'Опубликовать' }).click()
    await page.getByRole('button', { name: /Событие изменено/ }).click()
    await page.getByRole('button', { name: 'Удалить', exact: true }).click()
    await page.locator('.sheet').getByRole('button', { name: 'Удалить', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: /Событие изменено/ }).count(), 0)
    assert.deepEqual(errors, [])
    console.log('Teacher demo: code, event validation, edit, delete and chat privacy passed.')
  } finally { await browser.close() }
})().catch((e) => { console.error(e); process.exitCode = 1 })
