// Run with PLAYWRIGHT_CORE pointing to an installed playwright-core package.
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 320, height: 812 } })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  try {
    await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5190/')
    await page.evaluate(() => localStorage.clear())
    await page.reload()
    assert.match(await page.locator('body').innerText(), /Правила общения/)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.getByRole('button', { name: 'Начать', exact: true }).click()
    await page.locator('.check input').check()
    await page.getByRole('button', { name: 'Дальше', exact: true }).click()
    await page.getByRole('button', { name: /Заполнить пустые поля/ }).click()
    await page.locator('input[placeholder="9Б"]').fill('3А')
    assert.equal(await page.locator('text=Телефон родителя').count(), 0)
    await page.getByRole('button', { name: 'Готово', exact: true }).click()
    await page.getByRole('button', { name: 'Пропустить' }).click()
    await page.locator('.tabbar button', { hasText: 'Чаты' }).click()
    await page.getByText('3А — наш класс', { exact: true }).click()
    if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/chat-320.png` })
    assert.equal(await page.locator('.tabbar').count(), 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.locator('textarea').fill('Всем привет')
    await page.locator('button.send').click()
    await page.waitForTimeout(2800)
    assert.equal(await page.locator('.typing').count(), 0)
    assert.equal(await page.locator('.msg-wrap').count(), 1)
    await page.goBack()
    await page.locator('.tabbar button', { hasText: 'События' }).click()
    if (process.env.SHOT_DIR) await page.screenshot({ path: `${process.env.SHOT_DIR}/events-320.png` })
    await page.getByRole('button', { name: 'Сообщить', exact: true }).click()
    assert.match(await page.locator('.sheet').innerText(), /не отправляется/)
    await page.locator('.sheet-bg').click({ position: { x: 5, y: 5 } })
    await page.locator('.tabbar button', { hasText: 'Профиль' }).click()
    await page.getByRole('button', { name: /Конфиденциальность/ }).click()
    assert.equal(await page.locator('text=Родительский контроль').count(), 0)
    await page.goBack()
    await page.getByRole('button', { name: /О приложении/ }).click()
    await page.getByRole('button', { name: /Посмотреть как учитель/ }).click()
    assert.match(await page.locator('.sheet').innerText(), /учебная проверка/i)
    assert.deepEqual(errors, [])
    console.log('Smoke test passed: mobile navigation, demo registration, class isolation, no parent features, local alerts and teacher code.')
  } finally { await browser.close() }
})().catch((error) => { console.error(error); process.exitCode = 1 })
